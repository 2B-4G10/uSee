// Release signing is read from android/keystore.properties or the
// USEE_KEYSTORE_* environment variables. When neither is present the release
// build falls back to the debug key so the APK is still installable for
// sideloading; such an APK must not be uploaded to a store.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv(env)

